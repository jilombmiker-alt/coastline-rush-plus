import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';

const root = process.env.LAN_TEST_URL ?? 'http://127.0.0.1:4182/';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const hostContext = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const guestContext = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const host = await hostContext.newPage();
const guest = await guestContext.newPage();
const errors = [];
host.on('pageerror', error => errors.push(`host: ${error.message}`));
guest.on('pageerror', error => errors.push(`guest: ${error.message}`));
try {
  await host.goto(root);
  await host.locator('#loading').waitFor({ state: 'hidden' });
  await host.selectOption('#track-select', 'storm');
  await host.selectOption('#mode-select', 'party');
  await host.click('#online-button');
  await host.fill('#lan-name', '测试房主');
  await host.uncheck('#lan-ai');
  await host.click('#lan-create');
  await host.waitForFunction(() => !!document.querySelector('#lan-room-code')?.textContent || !!document.querySelector('#lan-error')?.textContent, null, { timeout: 8000 });
  assert.equal(await host.locator('#lan-error').innerText(), '');
  const code = await host.locator('#lan-room-code').innerText();
  assert.match(code, /^[A-F0-9]{6}$/);
  await host.check('#lan-ai-room');
  await host.waitForFunction(() => document.querySelector('#lan-room-config')?.textContent?.includes('AI 补位'));
  await host.uncheck('#lan-ai-room');
  await host.waitForFunction(() => document.querySelector('#lan-room-config')?.textContent?.includes('只和朋友比赛'));
  await guest.goto(`${root}?room=${code}`);
  await guest.locator('#loading').waitFor({ state: 'hidden' });
  await guest.locator('#lan-dialog').waitFor({ state: 'visible' });
  await guest.fill('#lan-name', '测试好友');
  await guest.click('#lan-join');
  await host.locator('#lan-roster > div').last().waitFor();
  assert.equal(await host.locator('#lan-roster > div').count(), 2);
  assert.equal(await guest.locator('#lan-roster > div').count(), 2);
  assert.equal(await guest.locator('#lan-ai-room').isDisabled(), true);
  assert.match(await guest.locator('#lan-room-config').innerText(), /AI|朋友/);
  await host.screenshot({ path: 'work/lan-lobby.png' });
  await host.click('#lan-start');
  await host.locator('#hud').waitFor({ state: 'visible' });
  await guest.locator('#hud').waitFor({ state: 'visible' });
  await host.waitForTimeout(3500);
  await host.keyboard.down('w');
  await host.keyboard.down('ArrowRight');
  await guest.keyboard.down('w');
  await guest.keyboard.down('ArrowLeft');
  await host.waitForTimeout(900);
  await host.keyboard.up('w'); await host.keyboard.up('ArrowRight');
  await guest.keyboard.up('w'); await guest.keyboard.up('ArrowLeft');
  const hostSpeed = Number(await host.locator('#speed').innerText());
  const guestSpeed = Number(await guest.locator('#speed').innerText());
  assert.ok(hostSpeed > 10, `host speed ${hostSpeed}`);
  assert.ok(guestSpeed > 10, `guest speed ${guestSpeed}`);
  assert.equal(await host.locator('#leaderboard .leader-row').count(), 2);
  assert.equal(await guest.locator('#leaderboard .leader-row').count(), 2);
  assert.match(await host.locator('#hud-track-name').innerText(), /赤霞/);
  assert.equal(errors.length, 0, errors.join('\n'));
  await host.screenshot({ path: 'work/lan-host.png' });
  await guest.screenshot({ path: 'work/lan-guest.png' });
  console.log(JSON.stringify({ room: code, hostSpeed, guestSpeed, errors, screenshots: ['work/lan-lobby.png', 'work/lan-host.png', 'work/lan-guest.png'] }));
} finally {
  await browser.close();
}
